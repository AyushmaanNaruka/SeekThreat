"""Rules, paths, and chokepoints.

CRITICAL: every edge carries the named rule that produced it and the evidence
supporting it. Both are validated here, so an edge without provenance cannot be
constructed. Edges are created by the deterministic rules engine only. The
language model never creates edges — it narrates paths that already exist.
"""

from __future__ import annotations

import hashlib
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, computed_field, field_validator

from packages.schema.models.provenance import Confidence

_CONFIDENCE_ORDER = {Confidence.LOW: 0, Confidence.MEDIUM: 1, Confidence.HIGH: 2}


def weakest(confidences: list[Confidence] | tuple[Confidence, ...]) -> Confidence:
    """The lowest confidence in a chain. A path is only as certain as its weakest step."""
    if not confidences:
        raise ValueError("no confidences to compare")
    return min(confidences, key=lambda c: _CONFIDENCE_ORDER[c])


class Rule(BaseModel):
    """One named inference rule. Rules are data so they can be cited and extended."""

    model_config = ConfigDict(frozen=True)

    name: str
    description: str
    preconditions: tuple[dict[str, str], ...]
    effect: str
    citation: str | None = None
    # How much an edge produced by this rule can be trusted, before evidence-specific
    # downgrades. Rules that rest on an assumption say so in `assumption`.
    confidence: Confidence
    assumption: str | None = None


class NodeKind(str, Enum):
    """What holding a node means for the attacker."""

    ATTACKER = "attacker"  # a foothold in an attacker-entry zone
    NETWORK_ACCESS = "network_access"  # can send packets to one observed service
    CODE_EXECUTION = "code_execution"  # can run code on one machine
    FILE_READ = "file_read"  # can read arbitrary files on one machine
    CREDENTIALS = "credentials"  # holds credential material taken from one machine


class GraphNode(BaseModel):
    """One attacker state in the graph."""

    model_config = ConfigDict(frozen=True)

    node_id: str
    kind: NodeKind
    label: str
    # The machine this state is about (canonical asset id or declared multi-homed name).
    machine: str | None = None
    zones: tuple[str, ...] = ()
    goal: bool = False


class PathEdge(BaseModel):
    """One step in an attack path, with the rule and evidence that produced it."""

    model_config = ConfigDict(frozen=True)

    from_node: str
    to_node: str
    rule_name: str
    # Prefixed ids: "obs:..." observations, "finding:..." findings, "topology:..." the
    # declared network model. At least one is required.
    evidence: tuple[str, ...]
    description: str = ""
    confidence: Confidence
    # Findings this step depends on. Remediating any of them removes the step.
    finding_ids: tuple[str, ...] = ()

    @field_validator("rule_name")
    @classmethod
    def _rule_is_named(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("rule_name must name the rule that produced this edge")
        return value

    @field_validator("evidence")
    @classmethod
    def _evidence_is_present(cls, value: tuple[str, ...]) -> tuple[str, ...]:
        if not value:
            raise ValueError("evidence must cite at least one observation or finding")
        return value

    @computed_field  # type: ignore[prop-decorator]
    @property
    def edge_id(self) -> str:
        """Content-derived id: the same step from the same facts always has the same id."""
        material = "\x1f".join(
            (self.from_node, self.to_node, self.rule_name, *sorted(self.evidence))
        )
        return "edge:" + hashlib.sha256(material.encode()).hexdigest()[:16]


class AttackPath(BaseModel):
    """A proven chain of steps. Narration is attached strictly downstream."""

    model_config = ConfigDict(frozen=True)

    path_id: str
    edges: tuple[PathEdge, ...]
    # Unranked until a path-scoring formula is signed off (DECISIONS.md D-039). None
    # means "not scored", never "scored zero".
    score: float | None = None
    # Position in the ranked path list (1 = look at first) and the sentence explaining
    # it (D-047). The ranking is ordinal: no weights, no composite number.
    rank: int | None = None
    rank_explanation: str | None = None
    # Generated by the model from the proven path above. Never the reverse.
    narration: str | None = None

    @field_validator("edges")
    @classmethod
    def _has_edges(cls, value: tuple[PathEdge, ...]) -> tuple[PathEdge, ...]:
        if not value:
            raise ValueError("an attack path needs at least one edge")
        for prev, nxt in zip(value, value[1:], strict=False):
            if prev.to_node != nxt.from_node:
                raise ValueError(
                    f"edges do not chain: {prev.to_node!r} is followed by {nxt.from_node!r}"
                )
        return value

    @computed_field  # type: ignore[prop-decorator]
    @property
    def confidence(self) -> Confidence:
        return weakest([e.confidence for e in self.edges])

    @computed_field  # type: ignore[prop-decorator]
    @property
    def entry_node(self) -> str:
        return self.edges[0].from_node

    @computed_field  # type: ignore[prop-decorator]
    @property
    def goal_node(self) -> str:
        return self.edges[-1].to_node


class Chokepoint(BaseModel):
    """One fix that breaks many paths. Ranked by how many."""

    finding_id: str
    paths_broken: list[str] = Field(default_factory=list)
    remediation: str
    rank: int
    # Goal nodes no attacker can reach any more once this finding is fixed. The primary
    # ranking key: path counts alone reward findings that sit on many detours.
    goals_cut: list[str] = Field(default_factory=list)
    asset_id: str | None = None
    cve_ids: tuple[str, ...] = ()


class UnclassifiedFinding(BaseModel):
    """A finding the rules could not turn into an attacker capability. Listed, never
    silently dropped, so the analyst sees what the graph does not cover."""

    model_config = ConfigDict(frozen=True)

    finding_id: str
    asset_id: str
    cve_ids: tuple[str, ...] = ()
    reason: str


class AttackGraphResult(BaseModel):
    """Everything one deterministic build produced. Contains no timestamps, so the same
    inputs serialise to byte-identical output."""

    model_config = ConfigDict(frozen=True)

    engagement_id: str
    topology_id: str
    rules_digest: str
    nodes: tuple[GraphNode, ...]
    edges: tuple[PathEdge, ...]
    paths: tuple[AttackPath, ...]
    chokepoints: tuple[Chokepoint, ...]
    unclassified_findings: tuple[UnclassifiedFinding, ...] = ()
    # Observed addresses that fall in no declared zone; no rule can place them.
    unzoned_addresses: tuple[str, ...] = ()
    max_depth: int
    max_paths: int
    # True when enumeration stopped at max_paths. Then the path list and chokepoint
    # counts are a deterministic prefix, not the full set.
    truncated: bool = False
    ordering: str = (
        "ranked (D-047): weakest-step confidence, then highest stored ERS on the path, "
        "then fewer steps, then edge ids"
    )


class SimulationResult(BaseModel):
    """What disappears when a set of findings is marked fixed and the graph is rebuilt."""

    model_config = ConfigDict(frozen=True)

    fixed_finding_ids: tuple[str, ...]
    baseline_path_count: int
    remaining_path_count: int
    removed_path_ids: tuple[str, ...]
    goals_no_longer_reachable: tuple[str, ...]
    after: AttackGraphResult
